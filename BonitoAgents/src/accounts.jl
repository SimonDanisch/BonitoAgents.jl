function accounts_section(auth::LoginAuth, session::Bonito.Session, state::ServerState)
    status = Observable("")
    secret = Observable{Any}("")
    # [verb, account, ""] from a row's ⋯ menu, ["groups", account, groups] from its field.
    action = Observable{Any}(nothing)
    shown(name, pw) = "Password for $(name), shown only now: $(pw)"
    on(session, action) do a
        a isa AbstractVector && length(a) == 3 || return
        verb, name, arg = String(a[1]), String(a[2]), String(a[3])
        admin_action!(status, () -> begin
            if verb == "password"
                secret[] = shown(name, reset_account_password!(state, name))
                "new password for $(name)"
            elseif verb == "authenticator"
                secret[] = DOM.div("Authenticator for $(name), shown only now:",
                                   authenticator_dom(register_authenticator!(state, name)))
                "new authenticator for $(name); the old one no longer works"
            elseif verb == "groups"
                set_account_groups!(state, name, parse_groups(arg)); "groups of $(name) saved"
            elseif verb == "disable"
                set_account_disabled!(state, name, true); "$(name) disabled; their open tabs were closed"
            elseif verb == "enable"
                set_account_disabled!(state, name, false); "$(name) enabled"
            elseif verb == "admin"
                set_account_admin!(state, name, true); "$(name) is an admin"
            elseif verb == "member"
                set_account_admin!(state, name, false); "$(name) is a member"
            elseif verb == "remove"
                remove_account!(state, name); "$(name) removed"
            else
                error("unknown account action '$(verb)'")
            end
        end)
    end

    # ── Add account: a form over the page ────────────────────────────────────
    adding = Observable(false)
    add = Observable(false)
    add_status = Observable("")
    new_name = Observable("")
    new_display = Observable("")
    new_email = Observable("")
    new_groups = Observable("")
    new_admin = Observable(false)
    on(session, adding) do open
        open && (add_status[] = "")
    end
    on(session, add) do _
        admin_action!(add_status, () -> begin
            groups = parse_groups(new_groups[])
            new_admin[] && union!(groups, ["admins"])
            login = add_account!(state, new_name[]; display_name = new_display[],
                                 email = new_email[], groups)
            # Shown under the table, where the form was opened from.
            secret[] = DOM.div(DOM.div(shown(new_name[], login.password)), authenticator_dom(login.authenticator))
            added = new_name[]
            new_name[] = ""; new_display[] = ""; new_email[] = ""; new_groups[] = ""; new_admin[] = false
            adding[] = false
            msg = "account $(added) added"
            safe_set!(status, msg)
            msg
        end)
    end
    add_form = modal(session, adding, "Add account") do
        field(label, obs, placeholder) = (DOM.label(label), text_input(obs, placeholder))
        DOM.div(
            field("Account", new_name, "login name, e.g. dave")...,
            field("Full name", new_display, "Dave Doe")...,
            field("Email", new_email, "optional")...,
            DOM.label("Groups"),
            group_picker(pickable_groups(state),
                         String[strip(g) for g in split(new_groups[], ',') if !isempty(strip(g))],
                         js"list => $(new_groups).notify(list.join(', '))"; allow_new = true),
            DOM.label("Admin"),
            DOM.label(DOM.input(type = "checkbox", checked = new_admin,
                                onchange = js"event => $(new_admin).notify(event.target.checked)"),
                      "may manage accounts, workers and settings"; class = "bt-form-check"),
            DOM.div("The password and authenticator are shown once, after adding.";
                    class = "bt-form-note"),
            admin_line(add_status, "bt-admin-status"),
            DOM.div(DOM.button("Cancel"; class = "bt-btn bt-btn-secondary",
                               onclick = js"event => $(adding).notify(false)"),
                    DOM.button("Add account"; class = "bt-btn bt-add-account-submit",
                               onclick = js"event => $(add).notify(true)");
                    class = "bt-form-actions");
            class = "bt-form")
    end

    # ── The table: who, their groups, their role; everything else in ⋯ ──────
    item(label, verb, name; danger = false, ask = "") = DOM.button(label;
        class = danger ? "bt-menu-item bt-menu-danger" : "bt-menu-item",
        onclick = js"""event => {
            $(Bonito.JSString(MENU_CLOSE_JS))
            const ask = $(ask);
            if (!ask || confirm(ask)) $(action).notify([$(verb), $(name), '']);
        }""")
    table = map(session, state.accounts) do accounts
        groups = pickable_groups(state)
        rows = map(sort!(collect(values(accounts)); by = a -> a.name)) do a
            admin = is_admin(a)
            DOM.tr(
                DOM.td(DOM.div(a.name; class = "bt-account-name"),
                       DOM.div(isempty(a.email) ? a.display_name : "$(a.display_name) · $(a.email)";
                               class = "bt-admin-muted bt-account-detail")),
                # Workers are shared with groups. `admins` is the role, kept as it is.
                DOM.td(group_picker(groups, filter(!=("admins"), a.groups),
                           js"""list => $(action).notify(['groups', $(a.name),
                                    list.concat($(admin) ? ['admins'] : []).join(', ')])""";
                           allow_new = true)),
                DOM.td(admin ? "admin" : "member",
                       a.disabled ? DOM.span("disabled"; class = "bt-pill bt-pill-warn bt-account-disabled") : nothing),
                DOM.td(action_menu(
                    item(admin ? "Make member" : "Make admin", admin ? "member" : "admin", a.name),
                    item(a.disabled ? "Enable" : "Disable", a.disabled ? "enable" : "disable", a.name),
                    DOM.div(; class = "bt-menu-sep"),
                    item("New password", "password", a.name),
                    item("New authenticator", "authenticator", a.name;
                         ask = "Replace the authenticator of $(a.name)? The codes of the old one stop working."),
                    DOM.div(; class = "bt-menu-sep"),
                    item("Remove", "remove", a.name; danger = true, ask = "Remove the account $(a.name)?");
                    title = "Actions for $(a.name)"); class = "bt-admin-menu-cell");
                class = a.disabled ? "bt-account-off" : "", dataAccount = a.name)
        end
        DOM.table(DOM.tr(DOM.th("Account"), DOM.th("Groups"), DOM.th("Role"), DOM.th("")),
                  rows...; class = "bt-admin-table bt-accounts-table")
    end
    return DOM.div(
        DOM.div(DOM.h2("Accounts"); class = "bt-section"),
        DOM.div(table,
                DOM.div(DOM.button("Add account…"; class = "bt-btn bt-btn-sm bt-add-account",
                                   onclick = js"event => $(adding).notify(true)"),
                        login_codes_button(auth.config, session);
                        class = "bt-admin-form"),
                admin_line(secret, "bt-admin-secret"),
                admin_line(status, "bt-admin-status");
                class = "bt-card"),
        add_form)
end

# Without mail, Authelia writes what it would have sent to a file on the server:
# notices about new devices, and the rare one-time code that confirms who someone
# is (the server registers everyone's authenticator, so adding a device normally
# needs none). Admins read it here.
login_codes_button(cfg::ProxyConfig, session::Bonito.Session) =
    cfg.smtp ? nothing : login_codes_button(notifications_file(cfg), session)

function login_codes_button(file::AbstractString, session::Bonito.Session)
    is_open = Observable(false)
    return DOM.div(
        DOM.button("Authelia's messages"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                   title = "What Authelia would have mailed; this server sends no mail",
                   onclick = js"event => $(is_open).notify(true)"),
        # Read on every open: it is the latest that matters.
        modal(session, is_open, "Authelia's messages") do
            text = isfile(file) ? read(file, String) : ""
            DOM.div(
                DOM.div("What Authelia would have mailed (this server sends no mail): notices " *
                        "about new devices, and now and then a one-time code someone needs to " *
                        "confirm who they are. Pass that on to the person it names.";
                        class = "bt-admin-muted"),
                DOM.pre(isempty(strip(text)) ? "Nothing yet." : text; class = "bt-admin-pre"))
        end)
end

invites_section(::OpenAuth, session::Bonito.Session, state::ServerState) = DOM.div()

function invites_section(::LoginAuth, session::Bonito.Session, state::ServerState)
    status = Observable("")
    link = Observable("")
    groups = Observable("")
    days = Observable("7")
    create = Observable(false)
    revoke = Observable("")
    on(session, create) do _
        admin_action!(status, () -> begin
            n = tryparse(Int, strip(days[]))
            (n === nothing || n < 1) && error("valid for: a number of days, at least 1")
            link[] = create_invite!(state, parse_groups(groups[]); valid_for = Day(n))
            "invite created; send the link to one person"
        end)
    end
    on(session, revoke) do id
        isempty(id) && return
        admin_action!(status, () -> revoke_invite!(state, id) ? "invite revoked" : "the invite was already gone")
    end
    table = map(session, state.invites) do invites
        open = sort!([i for i in values(invites) if i.expires > now(UTC)]; by = i -> i.created)
        isempty(open) && return DOM.div("No open invites."; class = "bt-admin-muted")
        rows = map(open) do i
            DOM.tr(DOM.td(i.created_by),
                   DOM.td(!isempty(i.account) ? "sets up $(i.account)" : isempty(i.groups) ? "member" : join(i.groups, ", ")),
                   DOM.td(Dates.format(i.created, "yyyy-mm-dd HH:MM")),
                   DOM.td(Dates.format(i.expires, "yyyy-mm-dd HH:MM")),
                   DOM.td(DOM.button("Revoke"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                                     onclick = js"event => $(revoke).notify($(i.id))")))
        end
        DOM.table(DOM.tr(DOM.th("Invited by"), DOM.th("Groups"), DOM.th("Created (UTC)"),
                         DOM.th("Expires (UTC)"), DOM.th("")), rows...; class = "bt-admin-table")
    end
    return DOM.div(
        DOM.div(DOM.h2("Invites"); class = "bt-section"),
        DOM.div(
            DOM.div("An invite link lets one person create their own account; they get " *
                    "their password on the page it opens.";
                    class = "bt-admin-muted"),
            DOM.div(DOM.span("Groups"; class = "bt-admin-muted"),
                    # `admins` is offered here: the invite then makes an admin.
                    map(session, state.accounts) do _
                        chosen = String[strip(g) for g in split(groups[], ',') if !isempty(strip(g))]
                        group_picker(vcat(pickable_groups(state), "admins"), chosen,
                                     js"list => $(groups).notify(list.join(', '))";
                                     empty = "member", allow_new = true)
                    end,
                    DOM.label("valid for ", DOM.input(type = "text", value = days, size = 3,
                              oninput = js"event => $(days).notify(event.target.value)"), " days"),
                    DOM.button("Create invite link"; class = "bt-btn bt-btn-sm",
                               onclick = js"event => $(create).notify(true)");
                    class = "bt-admin-form"),
            admin_line(link, "bt-admin-secret"),
            admin_line(status, "bt-admin-status"),
            table;
            class = "bt-card"))
end

"""
    adapters_section(session, state)

Which agent adapters workers keep installed, at which versions ("latest", or a
version), on which Node ("lts", a major, or a version). Saving sends the change to
every connected worker; each installs it once no chat runs there.
"""
function adapters_section(session::Bonito.Session, state::ServerState)
    spec = state.harness_spec[]
    spec === nothing && return DOM.div()
    status = Observable("")
    node = Observable(String(spec["node"]))
    packages = Dict{String,Observable{String}}(String(k) => Observable(String(v))
                                               for (k, v) in spec["packages"])
    save = Observable(false)
    on(session, save) do _
        admin_action!(status, () -> begin
            new = Dict{String,Any}("node" => String(strip(node[])),
                                   "packages" => Dict{String,Any}(k => String(strip(o[])) for (k, o) in packages))
            (isempty(new["node"]) || any(isempty, values(new["packages"]))) &&
                error("every version needs a value: \"latest\" or a version")
            set_harness_spec!(state, new)
            "saved; connected workers install it once no chat runs there"
        end)
    end
    row(label, obs) = DOM.div(DOM.span(label; class = "bt-settings-title"),
                              DOM.input(type = "text", value = obs,
                                        oninput = js"event => $(obs).notify(event.target.value)");
                              class = "bt-admin-form")
    return DOM.div(
        DOM.div(DOM.h2("Agent adapters"); class = "bt-section"),
        DOM.div(
            DOM.div("Workers install these themselves, with a private Node, and update them " *
                    "while no chat runs. \"latest\" follows the npm registry.";
                    class = "bt-admin-muted"),
            row("Node", node),
            (row(k, packages[k]) for k in sort!(collect(keys(packages))))...,
            DOM.button("Save"; class = "bt-btn bt-btn-sm", onclick = js"event => $(save).notify(true)"),
            admin_line(status, "bt-admin-status");
            class = "bt-card"))
end

"""
    worker_sharing_row(auth, session, state, worker_id)

Behind the proxy, on a worker's card: the groups it is shared with, editable by
whoever manages it.
"""
worker_sharing_row(::OpenAuth, session::Bonito.Session, state::ServerState, worker_id::String) = DOM.div()

function worker_sharing_row(::LoginAuth, session::Bonito.Session, state::ServerState, worker_id::String)
    w = get(state.workers[], worker_id, nothing)
    (w === nothing || !can_manage(state, w)) && return DOM.div()
    status = Observable("")
    groups = Observable(join(w.shared_with, ", "))
    on(session, groups) do text
        admin_action!(status, () -> begin
            share_worker!(state, worker_id, parse_groups(text))
            isempty(strip(text)) ? "not shared" : "shared"
        end)
    end
    # Re-drawn when accounts change, so a group made since is on the list. The
    # sharing itself is not an account change, so an open list stays open.
    picker = map(session, state.accounts) do _
        current = get(state.workers[], worker_id, w).shared_with
        # An admin may share with a group nobody is in yet; a member only with theirs.
        group_picker(pickable_groups(state), current, js"list => $(groups).notify(list.join(', '))";
                     empty = "nobody", allow_new = is_admin(state))
    end
    return DOM.div(
        DOM.span("Shared with"; class = "bt-admin-muted",
                 title = "Members of these groups start chats here, which run as this machine's user."),
        picker,
        DOM.span(status; class = "bt-admin-status"), AdminStyles;
        class = "bt-admin-form bt-worker-sharing")
end
