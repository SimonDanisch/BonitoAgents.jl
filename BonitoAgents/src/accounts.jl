"""
    worker_install_block(::ProxyAuth, session, state)

"Add worker" behind the proxy: an admin issues a credential and gets the install
command that carries it (shown once); the credentials issued so far can be
revoked. A member is told to ask an admin.
"""
function worker_install_block(::ProxyAuth, session::Bonito.Session, state::ServerState)
    summary = DOM.summary(DOM.span("Add a worker"; class = "bt-discover-title");
                          class = "bt-discover-header")
    if !is_admin(state)
        return DOM.details(summary,
            DOM.div("An admin adds workers: each machine gets its own credential.";
                    class = "bt-install-block bt-admin-muted");
            class = "bt-card bt-install-details")
    end
    base = install_base_url(state)
    issued = Observable{Any}(DOM.div())
    status = Observable("")
    add = Observable(false)
    revoke = Observable("")
    on(session, add) do _
        admin_action!(status, () -> begin
            cred = add_worker_credential!(state, state.user.name)
            unix = "curl -fsSL $(base)/install.sh | BONITOAGENTS_WORKER_CREDENTIAL='$(cred)' sh"
            win  = "\$env:BONITOAGENTS_WORKER_CREDENTIAL='$(cred)'; irm $(base)/install.ps1 | iex"
            issued[] = DOM.div(
                DOM.div("Run this on the new machine. It carries the worker's credential, " *
                        "shown only now; revoking it below disconnects that worker.";
                        class = "bt-admin-muted"),
                install_command_row("Linux / macOS", unix),
                install_command_row("Windows (PowerShell)", win);
                class = "bt-admin-secret")
            "credential $(first(split(cred, ':'))) issued"
        end)
    end
    on(session, revoke) do name
        isempty(name) && return
        admin_action!(status, () ->
            revoke_worker_credential!(state, name) ? "revoked $(name)" : "$(name) was already gone")
    end
    creds = map(session, state.worker_credentials, state.workers) do creds, workers
        isempty(creds) && return DOM.div("No worker credentials issued yet."; class = "bt-admin-muted")
        rows = map(sort!(collect(values(creds)); by = c -> c.created)) do c
            used = [w.name for w in values(workers) if w.credential == c.name]
            DOM.tr(DOM.td(DOM.code(c.name)), DOM.td(isempty(used) ? "not connected yet" : join(used, ", ")),
                   DOM.td(c.owner), DOM.td(Dates.format(c.created, "yyyy-mm-dd")),
                   DOM.td(DOM.button("Revoke"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                                     onclick = js"event => $(revoke).notify($(c.name))")))
        end
        DOM.table(DOM.tr(DOM.th("Credential"), DOM.th("Worker"), DOM.th("Issued by"),
                         DOM.th("Issued"), DOM.th("")), rows...; class = "bt-admin-table")
    end
    body = DOM.div(
        AdminStyles,
        DOM.button("Add worker"; class = "bt-btn bt-btn-sm",
                   onclick = js"event => $(add).notify(true)"),
        issued,
        DOM.div(status; class = "bt-admin-status"),
        creds;
        class = "bt-install-block")
    # `open` is a boolean attribute: present means open, whatever its value.
    return isempty(state.workers[]) ?
        DOM.details(summary, body; class = "bt-card bt-install-details", open = true) :
        DOM.details(summary, body; class = "bt-card bt-install-details")
end

"""
    account_sections(session, state)

The dashboard's account sections: everyone's own account behind the proxy, and
for admins the accounts, the invites and the agent adapter versions workers keep
installed.
"""
function account_sections(session::Bonito.Session, state::ServerState)
    state.user === nothing && return DOM.div()
    admin = is_admin(state)
    return DOM.div(AdminStyles,
                   own_account_section(state.auth, session, state),
                   admin ? accounts_section(state.auth, session, state) : DOM.div(),
                   admin ? invites_section(state.auth, session, state) : DOM.div(),
                   admin ? adapters_section(session, state) : DOM.div())
end

own_account_section(::LocalAuth, session::Bonito.Session, state::ServerState) = DOM.div()

function own_account_section(auth::ProxyAuth, session::Bonito.Session, state::ServerState)
    user = state.user
    cfg = auth.config
    status = Observable("")
    secret = Observable("")
    renew = Observable(false)
    on(session, renew) do _
        admin_action!(status, () -> begin
            secret[] = "Your new password, shown only now: " * reset_account_password!(state, user.name)
            "new password set"
        end)
    end
    groups = isempty(user.groups) ? "no groups" : "groups: " * join(user.groups, ", ")
    logout = public_origin(cfg, cfg.auth_domain) * "/logout?rd=" * HTTP.escapeuri(public_origin(cfg, cfg.domain))
    return DOM.div(
        DOM.div(DOM.h2("Your account"); class = "bt-section"),
        DOM.div(
            DOM.div("Signed in as $(user.display_name) ($(user.name)); $(groups)."),
            DOM.div(
                DOM.button("New password"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                           onclick = js"""event => {
                               if (confirm("Replace your password with a new, generated one?"))
                                   $(renew).notify(true);
                           }"""),
                DOM.a("Log out"; href = logout, class = "bt-btn bt-btn-sm bt-btn-secondary");
                class = "bt-admin-form"),
            DOM.div(secret; class = "bt-admin-secret"),
            DOM.div(status; class = "bt-admin-status");
            class = "bt-card"))
end

accounts_section(::LocalAuth, session::Bonito.Session, state::ServerState) = DOM.div()

function accounts_section(auth::ProxyAuth, session::Bonito.Session, state::ServerState)
    status = Observable("")
    secret = Observable("")
    # [verb, account, argument] from a row's buttons and group field.
    action = Observable{Any}(nothing)
    new_name = Observable("")
    new_display = Observable("")
    new_email = Observable("")
    new_groups = Observable("")
    new_admin = Observable(false)
    shown(name, pw) = "Password for $(name), shown only now: $(pw)"
    on(session, action) do a
        a isa AbstractVector && length(a) == 3 || return
        verb, name, arg = String(a[1]), String(a[2]), String(a[3])
        admin_action!(status, () -> begin
            if verb == "add"
                groups = parse_groups(new_groups[])
                new_admin[] && union!(groups, ["admins"])
                pw = add_account!(state, new_name[]; display_name = new_display[],
                                  email = new_email[], groups)
                secret[] = shown(new_name[], pw)
                added = new_name[]
                new_name[] = ""; new_display[] = ""; new_email[] = ""; new_groups[] = ""
                "account $(added) added"
            elseif verb == "password"
                secret[] = shown(name, reset_account_password!(state, name))
                "new password for $(name)"
            elseif verb == "groups"
                set_account_groups!(state, name, parse_groups(arg)); "groups of $(name) saved"
            elseif verb == "disable"
                set_account_disabled!(state, name, true); "$(name) disabled; their open tabs were closed"
            elseif verb == "enable"
                set_account_disabled!(state, name, false); "$(name) enabled"
            elseif verb == "admin"
                set_account_admin!(state, name, true); "$(name) is an admin"
            elseif verb == "member"
                set_account_admin!(state, name, false); "$(name) is a member"
            elseif verb == "remove"
                remove_account!(state, name); "$(name) removed"
            else
                error("unknown account action '$(verb)'")
            end
        end)
    end
    act(verb, name) = js"event => $(action).notify([$(verb), $(name), ''])"
    table = map(session, state.accounts) do accounts
        rows = map(sort!(collect(values(accounts)); by = a -> a.name)) do a
            DOM.tr(
                DOM.td(a.name), DOM.td(a.display_name), DOM.td(a.email),
                DOM.td(DOM.input(type = "text", value = join(filter(!=("admins"), a.groups), ", "),
                                 placeholder = "groups",
                                 title = "Comma-separated; Enter saves. Workers can be shared with a group.",
                                 onkeydown = js"""event => {
                                     if (event.key === 'Enter')
                                         $(action).notify(['groups', $(a.name),
                                             event.target.value + ($(is_admin(a)) ? ', admins' : '')]);
                                 }""")),
                DOM.td(is_admin(a) ? "admin" : "member"),
                DOM.td(a.disabled ? "disabled" : "active"),
                DOM.td(DOM.div(
                    DOM.button(is_admin(a) ? "Make member" : "Make admin";
                               class = "bt-btn bt-btn-sm bt-btn-secondary",
                               onclick = act(is_admin(a) ? "member" : "admin", a.name)),
                    DOM.button(a.disabled ? "Enable" : "Disable";
                               class = "bt-btn bt-btn-sm bt-btn-secondary",
                               onclick = act(a.disabled ? "enable" : "disable", a.name)),
                    DOM.button("New password"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                               onclick = act("password", a.name)),
                    DOM.button("Remove"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                               onclick = js"""event => {
                                   if (confirm("Remove the account " + $(a.name) + "?"))
                                       $(action).notify(['remove', $(a.name), '']);
                               }""");
                    class = "bt-admin-actions")))
        end
        DOM.table(DOM.tr(DOM.th("Account"), DOM.th("Name"), DOM.th("Email"), DOM.th("Groups"),
                         DOM.th("Role"), DOM.th("Status"), DOM.th("")), rows...; class = "bt-admin-table")
    end
    form = DOM.div(
        text_input(new_name, "account name"), text_input(new_display, "full name"),
        text_input(new_email, "email"), text_input(new_groups, "groups"),
        DOM.label(DOM.input(type = "checkbox", checked = new_admin,
                            onchange = js"event => $(new_admin).notify(event.target.checked)"),
                  " admin"),
        DOM.button("Add account"; class = "bt-btn bt-btn-sm",
                   onclick = js"event => $(action).notify(['add', $(new_name).value, ''])");
        class = "bt-admin-form")
    return DOM.div(
        DOM.div(DOM.h2("Accounts"); class = "bt-section"),
        DOM.div(table, form, DOM.div(secret; class = "bt-admin-secret"),
                DOM.div(status; class = "bt-admin-status"),
                login_codes_block(auth.config, session);
                class = "bt-card"))
end

# Without mail, Authelia writes the one-time code that confirms someone's new
# second factor to a file on the server; admins read it here and pass it on.
login_codes_block(cfg::ProxyConfig, session::Bonito.Session) =
    cfg.smtp ? DOM.div() : login_codes_block(notifications_file(cfg), session)

function login_codes_block(file::AbstractString, session::Bonito.Session)
    shown = Observable("")
    refresh = Observable(false)
    on(session, refresh) do _
        safe_set!(shown, isfile(file) ? read(file, String) : "Nothing yet.")
    end
    return DOM.details(
        DOM.summary("Login codes (this server sends no mail)"),
        DOM.div("Setting up a second factor asks for a code Authelia would have mailed. " *
                "The latest one is here; pass it on to the person it names.";
                class = "bt-admin-muted"),
        DOM.button("Show the latest"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                   onclick = js"event => $(refresh).notify(true)"),
        DOM.pre(shown; class = "bt-admin-pre"))
end

invites_section(::LocalAuth, session::Bonito.Session, state::ServerState) = DOM.div()

function invites_section(::ProxyAuth, session::Bonito.Session, state::ServerState)
    status = Observable("")
    link = Observable("")
    groups = Observable("")
    days = Observable("7")
    create = Observable(false)
    revoke = Observable("")
    on(session, create) do _
        admin_action!(status, () -> begin
            n = tryparse(Int, strip(days[]))
            (n === nothing || n < 1) && error("valid for: a number of days, at least 1")
            link[] = create_invite!(state, parse_groups(groups[]); valid_for = Day(n))
            "invite created; send the link to one person"
        end)
    end
    on(session, revoke) do id
        isempty(id) && return
        admin_action!(status, () -> revoke_invite!(state, id) ? "invite revoked" : "the invite was already gone")
    end
    table = map(session, state.invites) do invites
        open = sort!([i for i in values(invites) if i.expires > now(UTC)]; by = i -> i.created)
        isempty(open) && return DOM.div("No open invites."; class = "bt-admin-muted")
        rows = map(open) do i
            DOM.tr(DOM.td(i.created_by), DOM.td(isempty(i.groups) ? "member" : join(i.groups, ", ")),
                   DOM.td(Dates.format(i.created, "yyyy-mm-dd HH:MM")),
                   DOM.td(Dates.format(i.expires, "yyyy-mm-dd HH:MM")),
                   DOM.td(DOM.button("Revoke"; class = "bt-btn bt-btn-sm bt-btn-secondary",
                                     onclick = js"event => $(revoke).notify($(i.id))")))
        end
        DOM.table(DOM.tr(DOM.th("Invited by"), DOM.th("Groups"), DOM.th("Created (UTC)"),
                         DOM.th("Expires (UTC)"), DOM.th("")), rows...; class = "bt-admin-table")
    end
    return DOM.div(
        DOM.div(DOM.h2("Invites"); class = "bt-section"),
        DOM.div(
            DOM.div("An invite link lets one person create their own account; they get " *
                    "their password on the page it opens.";
                    class = "bt-admin-muted"),
            DOM.div(text_input(groups, "groups (\"admins\" for an admin)"),
                    DOM.label("valid for ", DOM.input(type = "text", value = days, size = 3,
                              oninput = js"event => $(days).notify(event.target.value)"), " days"),
                    DOM.button("Create invite link"; class = "bt-btn bt-btn-sm",
                               onclick = js"event => $(create).notify(true)");
                    class = "bt-admin-form"),
            DOM.div(link; class = "bt-admin-secret"),
            DOM.div(status; class = "bt-admin-status"),
            table;
            class = "bt-card"))
end

"""
    adapters_section(session, state)

Which agent adapters workers keep installed, at which versions ("latest", or a
version), on which Node ("lts", a major, or a version). Saving sends the change to
every connected worker; each installs it once no chat runs there.
"""
function adapters_section(session::Bonito.Session, state::ServerState)
    spec = state.harness_spec[]
    spec === nothing && return DOM.div()
    status = Observable("")
    node = Observable(String(spec["node"]))
    packages = Dict{String,Observable{String}}(String(k) => Observable(String(v))
                                               for (k, v) in spec["packages"])
    save = Observable(false)
    on(session, save) do _
        admin_action!(status, () -> begin
            new = Dict{String,Any}("node" => String(strip(node[])),
                                   "packages" => Dict{String,Any}(k => String(strip(o[])) for (k, o) in packages))
            (isempty(new["node"]) || any(isempty, values(new["packages"]))) &&
                error("every version needs a value: \"latest\" or a version")
            set_harness_spec!(state, new)
            "saved; connected workers install it once no chat runs there"
        end)
    end
    row(label, obs) = DOM.div(DOM.span(label; class = "bt-settings-title"),
                              DOM.input(type = "text", value = obs,
                                        oninput = js"event => $(obs).notify(event.target.value)");
                              class = "bt-admin-form")
    return DOM.div(
        DOM.div(DOM.h2("Agent adapters"); class = "bt-section"),
        DOM.div(
            DOM.div("Workers install these themselves, with a private Node, and update them " *
                    "while no chat runs. \"latest\" follows the npm registry.";
                    class = "bt-admin-muted"),
            row("Node", node),
            (row(k, packages[k]) for k in sort!(collect(keys(packages))))...,
            DOM.button("Save"; class = "bt-btn bt-btn-sm", onclick = js"event => $(save).notify(true)"),
            DOM.div(status; class = "bt-admin-status");
            class = "bt-card"))
end

"""
    worker_sharing_row(auth, session, state, worker_id)

Behind the proxy, on a worker's card: the groups it is shared with, editable by
whoever manages it.
"""
worker_sharing_row(::LocalAuth, session::Bonito.Session, state::ServerState, worker_id::String) = DOM.div()

function worker_sharing_row(::ProxyAuth, session::Bonito.Session, state::ServerState, worker_id::String)
    w = get(state.workers[], worker_id, nothing)
    (w === nothing || !can_manage(state, w)) && return DOM.div()
    status = Observable("")
    groups = Observable(join(w.shared_with, ", "))
    on(session, groups) do text
        admin_action!(status, () -> begin
            share_worker!(state, worker_id, parse_groups(text))
            isempty(strip(text)) ? "not shared" : "shared"
        end)
    end
    return DOM.div(
        DOM.span("Shared with"; class = "bt-admin-muted"),
        DOM.input(type = "text", value = groups, placeholder = "groups", size = 18,
                  title = "Comma-separated groups; Enter saves. Their members start chats here, " *
                          "which run as this machine's user.",
                  onkeydown = js"event => { if (event.key === 'Enter') $(groups).notify(event.target.value); }"),
        DOM.span(status; class = "bt-admin-status"), AdminStyles;
        class = "bt-admin-form")
end
