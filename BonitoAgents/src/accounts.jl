    html = """<!doctype html><html><head><meta charset="utf-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>$(esc_html(title))</title><style>
        body { font-family: system-ui, sans-serif; background: #f5f5f4; color: #1c1917; }
        main { max-width: 30rem; margin: 4rem auto; padding: 2rem; background: #fff; border-radius: 10px; }
        label { display: block; margin: 0.8rem 0; font-size: 0.9rem; }
        input { display: block; width: 100%; box-sizing: border-box; margin-top: 0.3rem; padding: 0.5rem;
                border: 1px solid #d6d3d1; border-radius: 6px; font-size: 1rem; }
        button { margin-top: 1rem; padding: 0.6rem 1.2rem; border: 0; border-radius: 6px;
                 background: #1c1917; color: #fff; font-size: 1rem; cursor: pointer; }
        .err { color: #b91c1c; }
        .pw { font-size: 1.2rem; padding: 0.3rem 0.5rem; background: #f5f5f4; user-select: all; }
        </style></head><body><main><h1>$(esc_html(title))</h1>$(body)</main></body></html>"""
    # The token is in the URL: no Referer carries it anywhere, nothing caches it.
    return HTTP.Response(status, ["Content-Type" => "text/html; charset=utf-8",
                                  "Cache-Control" => "no-store", "Referrer-Policy" => "no-referrer"];
                         body = html)
end

# An `application/x-www-form-urlencoded` body: `+` is a space there.
function form_fields(body::AbstractString)
    fields = Dict{String,String}()
    for pair in split(body, '&'; keepempty = false)
        k, v = occursin('=', pair) ? split(pair, '='; limit = 2) : (pair, "")
        fields[HTTP.unescapeuri(replace(k, '+' => ' '))] = HTTP.unescapeuri(replace(v, '+' => ' '))
    end
    return fields
end

# ── Who sees what ────────────────────────────────────────────────────────────

"""
    visible(state, chat_or_worker) -> Bool

May the person `state` serves see this chat or worker? Admins see everything,
members what they own, and the workers shared with a group they are in. The
server's own view (no user) sees everything.
"""
visible(state::ServerState, x) = visible(state.user, x)
visible(::Nothing, x) = true
visible(user::User, p::ProjectInfo) = is_admin(user) || p.owner == user.name
visible(user::User, w::WorkerInfo) =
    is_admin(user) || w.owner == user.name || !isdisjoint(w.shared_with, user.groups)

"Does `state` serve an admin? The server's own view (no user) acts as one."
is_admin(state::ServerState) = state.user === nothing || is_admin(state.user)

"May the person `state` serves rename, update, share or remove this worker?"
can_manage(state::ServerState, w::WorkerInfo) = can_manage(state.user, w)
can_manage(::Nothing, w::WorkerInfo) = true
can_manage(user::User, w::WorkerInfo) = is_admin(user) || w.owner == user.name

"""
    share_worker!(state, worker_id, groups)

Let the members of `groups` see the worker and start chats on it. Sharing a
worker shares its machine: their agents run there as the worker's user.
"""
function share_worker!(state::ServerState, worker_id::AbstractString, groups::Vector{String})
    root = root_state(state)
    lock(root.lock) do
        w = get(root.workers[], String(worker_id), nothing)
        w === nothing && error("there is no worker '$(worker_id)'")
        w.shared_with = groups
        save_workers!(root)
    end
    notify_workers!(root)
    @info "worker shared" worker_id groups
    return nothing
end

# Live browser sessions by user, so disabling an account can end them.
function register_user_session!(state::ServerState, session::Bonito.Session, user::User)
    root = root_state(state)
    lock(root.lock) do
        push!(get!(Vector{Bonito.Session}, root.user_sessions, user.name), session)
    end
    on(session.on_close) do closed
        closed || return
        lock(root.lock) do
            list = get(root.user_sessions, user.name, nothing)
            list === nothing || filter!(s -> s !== session, list)
        end
    end
    return nothing
end

function close_user_sessions!(state::ServerState, name::AbstractString)
    root = root_state(state)
    sessions = lock(() -> pop!(root.user_sessions, String(name), Bonito.Session[]), root.lock)
    foreach(close, sessions)
    return length(sessions)
end

# ── Agent adapters ───────────────────────────────────────────────────────────

"""
    set_harness_spec!(state, spec)

Change which agent adapters workers keep installed, and at which versions:
persisted, and sent to every connected worker right away (a worker that is
offline gets it with its next hello acknowledgement).
"""
function set_harness_spec!(state::ServerState, spec::Dict{String,Any})
    root = root_state(state)
    root.harness_spec[] = spec
    save_settings!(root)
    links = lock(() -> collect(root.worker_links), root.lock)
    for (wid, link) in links
        WorkerLink.state(link) === :connected || continue
        try
            send_command(root, wid, Dict("type" => "harness_spec", "spec" => spec))
        catch e
            # The worker dropped between the check and the send; its next hello
            # acknowledgement carries the spec.
            (e isa WebSockets.WebSocketError || e isa WorkerLink.LinkDead) || rethrow()
        end
    end
    return nothing
end

