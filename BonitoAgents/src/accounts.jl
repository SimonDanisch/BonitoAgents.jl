# ── Accounts, invites, worker credentials ────────────────────────────────────
# Behind the proxy the server owns what Caddy and Authelia know about machines
# and people (identity.jl): the worker credentials, rendered into the Caddyfile,
# and the accounts, rendered into Authelia's users database. It also decides
# which agent adapters workers keep installed. This file keeps those records,
# pushes them into the proxy's config, serves the invite pages, and draws the
# account controls on the dashboard. Nothing here checks a password: Caddy and
# Authelia do.
#
# Passwords are the server's alone. Authelia's own "reset password" and "change
# password" would write the users database behind the server's back, so the
# installer turns them off; a password is generated by Authelia (`--random`) and
# handed out once: to an admin, to a new account on its invite page, or to
# someone who asks for a new one on their account card.

credentials_file(s::ServerState) = joinpath(s.state_dir, "worker_credentials.json")
accounts_file(s::ServerState)    = joinpath(s.state_dir, "accounts.json")
invites_file(s::ServerState)     = joinpath(s.state_dir, "invites.json")

# Records of one kind from a JSON list; a malformed entry is skipped, not fatal.
function load_records!(into::AbstractDict, path::AbstractString, label::AbstractString, T::Type)
    raw = load_json_tolerant(String(path), label)
    raw === nothing && return nothing
    for d in raw
        try
            r = T(d)
            into[record_key(r)] = r
        catch e
            (e isa KeyError || e isa MethodError || e isa ArgumentError) || rethrow()
            @warn "skipping malformed entry in $(label)" exception = e
        end
    end
    return nothing
end

load_worker_credentials!(s::ServerState) =
    load_records!(s.worker_credentials[], credentials_file(s), "worker_credentials.json", WorkerCredential)
load_accounts!(s::ServerState) =
    load_records!(s.accounts[], accounts_file(s), "accounts.json", Account)
load_invites!(s::ServerState) =
    load_records!(s.invites[], invites_file(s), "invites.json", Invite)

save_worker_credentials!(s::ServerState) = lock(s.lock) do
    atomic_write_json(credentials_file(s), [Dict(c) for c in values(s.worker_credentials[])]; mode = 0o600)
end
save_accounts!(s::ServerState) = lock(s.lock) do
    atomic_write_json(accounts_file(s), [Dict(a) for a in values(s.accounts[])]; mode = 0o600)
end
save_invites!(s::ServerState) = lock(s.lock) do
    atomic_write_json(invites_file(s), [Dict(i) for i in values(s.invites[])]; mode = 0o600)
end

proxy_config(auth::ProxyAuth) = auth.config
proxy_config(::LocalAuth) =
    error("this server has no proxy in front (no proxy.json): there are no accounts or worker credentials to manage")

# Authelia's files live together, beside its users database. Without mail it
# writes what it would send (the one-time code that confirms a new second factor)
# to the notifications file.
notifications_file(cfg::ProxyConfig)   = joinpath(dirname(cfg.users_file), "notifications.txt")
authelia_config_file(cfg::ProxyConfig) = joinpath(dirname(cfg.users_file), "configuration.yml")

# Authelia's secrets, made once and kept in the state dir: a new session secret
# would log everyone out, a new storage key would leave its database unreadable.
authelia_secrets(state_dir::AbstractString) = (
    jwt     = bytes2hex(load_or_create_secret(state_dir, "authelia_jwt_secret")),
    session = bytes2hex(load_or_create_secret(state_dir, "authelia_session_secret")),
    storage = bytes2hex(load_or_create_secret(state_dir, "authelia_storage_key")))

smtp_settings(state_dir::AbstractString) =
    isfile(smtp_file(state_dir)) ? JSON.parsefile(smtp_file(state_dir)) : nothing

"""
    apply_proxy!(state)

Behind the proxy: write the Caddyfile, Authelia's users database and Authelia's
configuration from the server's records. Caddy (running with `--watch`) and
Authelia (watching its users file) reread the first two when they change; the
configuration only changes with `proxy.json`, which the installer follows with
a restart. A Caddyfile Caddy would reject is not written: it keeps serving the
last good one, and the error reaches whoever changed it. Without the proxy there
is nothing to do.
"""
apply_proxy!(state::ServerState) = apply_proxy!(state.auth, root_state(state))
apply_proxy!(::LocalAuth, ::ServerState) = nothing

function apply_proxy!(auth::ProxyAuth, root::ServerState)
    cfg = auth.config
    caddyfile, users = lock(root.lock) do
        (render_caddyfile(auth, values(root.worker_credentials[])),
         render_users_yaml(values(root.accounts[])))
    end
    candidate = cfg.caddyfile * ".new"
    atomic_write(io -> write(io, caddyfile), candidate; mode = 0o600)
    try
        check_caddyfile(cfg, candidate)
    catch
        rm(candidate; force = true)
        rethrow()
    end
    mv(candidate, cfg.caddyfile; force = true)
    atomic_write(io -> write(io, users), cfg.users_file; mode = 0o600)
    authelia = render_authelia_config(cfg, authelia_secrets(root.state_dir), smtp_settings(root.state_dir))
    atomic_write(io -> write(io, authelia), authelia_config_file(cfg); mode = 0o600)
    return nothing
end

# ── Worker credentials ───────────────────────────────────────────────────────

"""
    add_worker_credential!(state, owner) -> String

Issue a worker credential for `owner` ("Add worker"): Caddy checks it on `/w`
from now on. Returns `name:password`, the only time the password exists outside
its hash; the install command carries it to the new machine.
"""
function add_worker_credential!(state::ServerState, owner::AbstractString)
    root = root_state(state)
    cfg = proxy_config(root.auth)
    name = "w-" * bytes2hex(rand(Random.RandomDevice(), UInt8, 4))
    password = bytes2hex(rand(Random.RandomDevice(), UInt8, 24))
    cred = WorkerCredential(name, caddy_hash(cfg, password), String(owner), now(UTC))
    lock(root.lock) do
        root.worker_credentials[][name] = cred
        save_worker_credentials!(root)
    end
    apply_proxy!(root)
    safe_notify!(root.worker_credentials)
    @info "worker credential issued" name owner
    return name * ":" * password
end

"""
    revoke_worker_credential!(state, name) -> Bool

Take a worker credential back: Caddy refuses it from now on, and a worker that
is connected with it is disconnected (its reconnect meets the refusal).
"""
function revoke_worker_credential!(state::ServerState, name::AbstractString)
    root = root_state(state)
    removed = lock(root.lock) do
        c = pop!(root.worker_credentials[], String(name), nothing)
        c === nothing || save_worker_credentials!(root)
        c
    end
    removed === nothing && return false
    apply_proxy!(root)
    safe_notify!(root.worker_credentials)
    for (wid, w) in lock(() -> collect(root.workers[]), root.lock)
        w.credential == name || continue
        link = worker_link(root, wid)
        link === nothing || WorkerLink.kill!(link, "the worker's credential was revoked")
    end
    @info "worker credential revoked" name
    return true
end

# ── Accounts ─────────────────────────────────────────────────────────────────

# Change the accounts, then persist them and hand them to Authelia.
function update_accounts!(f::Function, state::ServerState)
    root = root_state(state)
    proxy_config(root.auth)
    lock(root.lock) do
        f(root.accounts[])
        save_accounts!(root)
    end
    apply_proxy!(root)
    safe_notify!(root.accounts)
    return nothing
end

function account(state::ServerState, name::AbstractString)
    a = lock(() -> get(root_state(state).accounts[], String(name), nothing), state.lock)
    a === nothing && error("there is no account '$(name)'")
    return a
end

# The server must keep an admin who can log in, and nobody locks themselves out.
function check_admin_remains(state::ServerState, name::AbstractString)
    state.user !== nothing && state.user.name == name &&
        error("you cannot do that to your own account")
    others = lock(state.lock) do
        count(a -> a.name != name && is_admin(a) && !a.disabled, values(root_state(state).accounts[]))
    end
    others == 0 && error("'$(name)' is the last admin who can log in")
    return nothing
end

"""
    add_account!(state, name; display_name, email, groups) -> String

A new login in `groups` ("admins" makes an admin), accepted by Authelia once it
rereads its users database (it watches the file). Returns the account's
password, generated by Authelia, for its owner; it exists nowhere else.
"""
function add_account!(state::ServerState, name::AbstractString;
                      display_name::AbstractString = name, email::AbstractString = "",
                      groups::Vector{String} = String[])
    cfg = proxy_config(state.auth)
    valid_name(name) ||
        error("an account name is letters, digits, '.', '_' and '-' (got '$(name)')")
    haskey(root_state(state).accounts[], name) && error("there is an account '$(name)' already")
    pw = authelia_random_password(cfg)
    acct = Account(String(name), isempty(display_name) ? String(name) : String(display_name),
                   String(email), groups, false, pw.hash)
    update_accounts!(state) do accounts
        # Checked again under the lock: two requests for one name, one account.
        haskey(accounts, acct.name) && error("there is an account '$(acct.name)' already")
        accounts[acct.name] = acct
    end
    @info "account added" name groups
    return pw.password
end

"A new random password for `name`, generated by Authelia; returned once."
function reset_account_password!(state::ServerState, name::AbstractString)
    a = account(state, name)
    pw = authelia_random_password(proxy_config(state.auth))
    update_accounts!(_ -> (a.password_hash = pw.hash), state)
    return pw.password
end

"""
    set_account_disabled!(state, name, disabled)

Authelia refuses a disabled account's next request; its open tabs are closed here,
since an open websocket is never re-checked.
"""
function set_account_disabled!(state::ServerState, name::AbstractString, disabled::Bool)
    a = account(state, name)
    disabled && is_admin(a) && check_admin_remains(state, name)
    update_accounts!(_ -> (a.disabled = disabled), state)
    disabled && close_user_sessions!(state, name)
    return nothing
end

"""
    set_account_groups!(state, name, groups)

Put `name` in exactly `groups`. "admins" makes an admin; any other group is one
workers can be shared with (`share_worker!`).
"""
function set_account_groups!(state::ServerState, name::AbstractString, groups::Vector{String})
    a = account(state, name)
    is_admin(a) && !("admins" in groups) && check_admin_remains(state, name)
    update_accounts!(_ -> (a.groups = groups), state)
    # The groups arrive with the next request through Authelia: reload the tabs.
    close_user_sessions!(state, name)
    return nothing
end

set_account_admin!(state::ServerState, name::AbstractString, admin::Bool) =
    set_account_groups!(state, name, admin ? union(account(state, name).groups, ["admins"]) :
                                             setdiff(account(state, name).groups, ["admins"]))

function remove_account!(state::ServerState, name::AbstractString)
    a = account(state, name)
    is_admin(a) && check_admin_remains(state, name)
    state.user !== nothing && state.user.name == name && error("you cannot remove your own account")
    update_accounts!(accounts -> delete!(accounts, a.name), state)
    close_user_sessions!(state, name)
    return nothing
end

"Every group some account is in, sorted."
all_groups(state::ServerState) =
    sort!(unique!(String[g for a in values(root_state(state).accounts[]) for g in a.groups]))

# ── Invites ──────────────────────────────────────────────────────────────────

"""
    create_invite!(state, groups; valid_for = Day(7)) -> String

A link that lets one person create their own account in `groups`, valid for
`valid_for`. The link is returned here only; the server keeps its token's hash.
"""
function create_invite!(state::ServerState, groups::Vector{String}; valid_for::Period = Day(7))
    root = root_state(state)
    proxy_config(root.auth)
    token = bytes2hex(rand(Random.RandomDevice(), UInt8, 32))
    t = now(UTC)
    invite = Invite(invite_id(token), groups, acting_owner(state), t, t + valid_for)
    lock(root.lock) do
        filter!(((_, i),) -> i.expires > t, root.invites[])   # expired ones go with it
        root.invites[][invite.id] = invite
        save_invites!(root)
    end
    safe_notify!(root.invites)
    @info "invite created" groups by = invite.created_by expires = invite.expires
    return install_base_url(root) * "/invite/" * token
end

function revoke_invite!(state::ServerState, id::AbstractString)
    root = root_state(state)
    removed = lock(root.lock) do
        i = pop!(root.invites[], String(id), nothing)
        i === nothing || save_invites!(root)
        i
    end
    removed === nothing && return false
    safe_notify!(root.invites)
    return true
end

"The invite a link carries, while it is good for an account; `nothing` otherwise."
function open_invite(state::ServerState, token::AbstractString)
    i = lock(() -> get(root_state(state).invites[], invite_id(token), nothing), state.lock)
    return (i === nothing || i.expires <= now(UTC)) ? nothing : i
end

"""
    redeem_invite!(state, token, name; display_name, email) -> String

Create the account an invite link offers, and use the link up. Returns the new
account's password, which its owner sees once.
"""
function redeem_invite!(state::ServerState, token::AbstractString, name::AbstractString;
                        display_name::AbstractString = name, email::AbstractString = "")
    root = root_state(state)
    id = invite_id(token)
    # Taken out first, so two submissions of one link cannot make two accounts.
    invite = lock(() -> pop!(root.invites[], id, nothing), root.lock)
    invite === nothing && error("this invite link was used already or revoked")
    if invite.expires <= now(UTC)
        save_invites!(root)
        safe_notify!(root.invites)
        error("this invite link has expired")
    end
    password = try
        add_account!(root, name; display_name, email, groups = invite.groups)
    catch e
        # A name that is taken or not allowed: the link stays good for another try.
        lock(() -> (root.invites[][id] = invite), root.lock)
        rethrow()
    end
    save_invites!(root)
    safe_notify!(root.invites)
    @info "invite used" name invited_by = invite.created_by
    return password
end

# /invite/<token>: open to anyone (the token is the proof), so it is plain HTML
# with a form, no dashboard session.
const INVITE_ROUTE_RE = r"^/invite/([0-9a-f]{64})/?(?:$|\?)"

function add_invite_routes!(srv::Bonito.Server, state::ServerState)
    Bonito.route!(srv, INVITE_ROUTE_RE => function(context)
        invite_response(state.auth, state, context.request, String(context.match.captures[1]))
    end)
end

invite_response(::LocalAuth, state::ServerState, request, token::AbstractString) =
    invite_page(404, "Not found", "<p>This server has no accounts to invite anyone to.</p>")

function invite_response(auth::ProxyAuth, state::ServerState, request, token::AbstractString)
    open_invite(state, token) === nothing && return invite_page(404, "This invite is not valid",
        "<p>The link was used already, revoked, or has expired. Ask for a new one.</p>")
    request.method == "POST" ||
        return invite_page(200, "Create your account", invite_form(Dict{String,String}(), ""))
    form = form_fields(String(request.body))
    name = strip(get(form, "name", ""))
    display_name = strip(get(form, "display_name", ""))
    password = try
        redeem_invite!(state, token, name; display_name = isempty(display_name) ? name : display_name,
                       email = strip(get(form, "email", "")))
    catch e
        (e isa ErrorException || e isa ProcessFailedException || e isa Base.IOError) || rethrow()
        return invite_page(400, "Create your account",
                           invite_form(form, first(split(sprint(showerror, e), '\n'))))
    end
    cfg = auth.config
    second_factor = cfg.smtp ?
        "Authelia emails you a code to confirm it." :
        "Authelia confirms it with a one-time code; this server sends no mail, so ask an admin for it."
    return invite_page(200, "Your account is ready", """
        <p>Account <b>$(esc_html(name))</b>. Your password, shown only now:</p>
        <p><code class="pw">$(esc_html(password))</code></p>
        <p>Store it in your password manager, then <a href="$(esc_html(public_origin(cfg, cfg.domain)))">log in</a>.
        At the first login you set up a second factor (an authenticator app or a security key).
        $(second_factor)</p>""")
end

function invite_form(form::AbstractDict, error_message::AbstractString)
    field(key, label, type = "text") = """
        <label>$(label)<input type="$(type)" name="$(key)" value="$(esc_html(get(form, key, "")))"></label>"""
    err = isempty(error_message) ? "" : "<p class=\"err\">$(esc_html(error_message))</p>"
    return """
        $(err)
        <form method="post">
        $(field("name", "Account name (letters, digits, '.', '_', '-')"))
        $(field("display_name", "Full name"))
        $(field("email", "Email", "email"))
        <button type="submit">Create account</button>
        </form>"""
end

