# ── Accounts, invites, worker credentials ────────────────────────────────────
# Behind the proxy or a tunnel the server owns what Authelia (and Caddy) know
# about machines and people (identity.jl): the accounts, rendered into Authelia's
# users database, and the worker credentials, rendered into the Caddyfile behind
# the proxy. It also decides which agent adapters workers keep installed. This
# file keeps those records, pushes them into the login's config, serves the
# invite pages, and draws the account controls on the dashboard. Nothing here
# checks a password: Authelia does (and Caddy, a worker's, behind the proxy).
#
# Passwords are the server's alone. Authelia's own "reset password" and "change
# password" would write the users database behind the server's back, so the
# installer turns them off; a password is generated by Authelia (`--random`) and
# handed out once: to an admin, to a new account on its invite page, or to
# someone who asks for a new one on their account card.

credentials_file(s::ServerState) = joinpath(s.state_dir, "worker_credentials.json")
accounts_file(s::ServerState)    = joinpath(s.state_dir, "accounts.json")
invites_file(s::ServerState)     = joinpath(s.state_dir, "invites.json")

# Records of one kind from a JSON list; a malformed entry is skipped, not fatal.
function load_records!(into::AbstractDict, path::AbstractString, label::AbstractString, T::Type)
    raw = load_json_tolerant(String(path), label)
    raw === nothing && return nothing
    for d in raw
        try
            r = T(d)
            into[record_key(r)] = r
        catch e
            (e isa KeyError || e isa MethodError || e isa ArgumentError) || rethrow()
            @warn "skipping malformed entry in $(label)" exception = e
        end
    end
    return nothing
end

load_worker_credentials!(s::ServerState) =
    load_records!(s.worker_credentials[], credentials_file(s), "worker_credentials.json", WorkerCredential)
load_accounts!(s::ServerState) =
    load_records!(s.accounts[], accounts_file(s), "accounts.json", Account)
load_invites!(s::ServerState) =
    load_records!(s.invites[], invites_file(s), "invites.json", Invite)

save_worker_credentials!(s::ServerState) = lock(s.lock) do
    atomic_write_json(credentials_file(s), [Dict(c) for c in values(s.worker_credentials[])]; mode = 0o600)
end
save_accounts!(s::ServerState) = lock(s.lock) do
    atomic_write_json(accounts_file(s), [Dict(a) for a in values(s.accounts[])]; mode = 0o600)
end
save_invites!(s::ServerState) = lock(s.lock) do
    atomic_write_json(invites_file(s), [Dict(i) for i in values(s.invites[])]; mode = 0o600)
end

proxy_config(auth::LoginAuth) = auth.config
proxy_config(::OpenAuth) =
    error("this server has no login proxy in front (no proxy.json): there are no accounts to manage")

# The hash Caddy checks a worker's password against: behind the proxy only. On a
# trusted network and behind a tunnel the server checks the credential's digest
# itself; on one machine no worker needs a credential.
caddy_password_hash(auth::ProxyAuth, password::AbstractString) = caddy_hash(auth.config, password)
caddy_password_hash(::Union{NetworkAuth,TunnelAuth}, password::AbstractString) = ""
caddy_password_hash(::LocalAuth, password::AbstractString) =
    error("only this machine reaches this server (it listens on localhost), and its workers need " *
          "no credential. To add other machines, listen on the network (--host 0.0.0.0) or put " *
          "the login proxy in front (install_server.sh).")

# Authelia's files live together, beside its users database. Without mail it
# writes what it would send (the one-time code that confirms a new second factor)
# to the notifications file.
notifications_file(cfg::ProxyConfig)   = joinpath(dirname(cfg.users_file), "notifications.txt")
authelia_config_file(cfg::ProxyConfig) = joinpath(dirname(cfg.users_file), "configuration.yml")
# Authelia's log, which the debug tools read back (`bt_dev_logs source="authelia"`)
# like the server's own: journald exists on some machines and is readable by few.
authelia_log_file(cfg::ProxyConfig)    = joinpath(dirname(cfg.users_file), "authelia.log")

"""
    watch_authelia_log!(state)

Keep Authelia's log to two generations, like the server's own, for as long as
the server runs. Authelia holds the file open for appending, so the server
copies it aside and truncates it in place (`rotate_by_copy!`); Authelia goes on
writing at the new end.
"""
watch_authelia_log!(state::ServerState) = watch_authelia_log!(state.auth, state)
watch_authelia_log!(::OpenAuth, ::ServerState) = nothing
function watch_authelia_log!(auth::LoginAuth, state::ServerState; every::Real = 600.0,
                             max_bytes::Integer = BonitoWorker.LOG_MAX_BYTES)
    path = authelia_log_file(auth.config)
    return Base.errormonitor(@async while Bonito.HTTPServer.isrunning(state.srv)
        rotate_by_copy!(path, max_bytes)
        sleep(every)
    end)
end

function rotate_by_copy!(path::AbstractString, max_bytes::Integer)
    (isfile(path) && filesize(path) > max_bytes) || return false
    cp(path, path * ".1"; force = true)
    open(identity, path, "w")          # truncated in place: the writer keeps its descriptor
    return true
end

# Authelia's secrets, made once and kept in the state dir: a new session secret
# would log everyone out, a new storage key would leave its database unreadable.
authelia_secrets(state_dir::AbstractString) = (
    jwt     = bytes2hex(load_or_create_secret(state_dir, "authelia_jwt_secret")),
    session = bytes2hex(load_or_create_secret(state_dir, "authelia_session_secret")),
    storage = bytes2hex(load_or_create_secret(state_dir, "authelia_storage_key")))

smtp_settings(state_dir::AbstractString) =
    isfile(smtp_file(state_dir)) ? JSON.parsefile(smtp_file(state_dir)) : nothing

"""
    apply_proxy!(state)

Behind the proxy or a tunnel: write Authelia's users database and configuration,
and behind the proxy the Caddyfile, from the server's records. Caddy (running
with `--watch`) and Authelia (watching its users file) reread the Caddyfile and
the users database when they change; the configuration only changes with
`proxy.json`, which the installer follows with a restart. A Caddyfile Caddy
would reject is not written: it keeps serving the last good one, and the error
reaches whoever changed it. Without a login there is nothing to do.
"""
apply_proxy!(state::ServerState) = apply_proxy!(state.auth, root_state(state))
apply_proxy!(::OpenAuth, ::ServerState) = nothing

function apply_proxy!(auth::LoginAuth, root::ServerState)
    cfg = auth.config
    writer = root.proxy_writer
    # Rendered and written as one step, one writer at a time: two changes at
    # once must not leave the earlier state on disk.
    lock(writer.lock) do
        write_front!(auth, root)
        users = lock(() -> render_users_yaml(values(root.accounts[])), root.lock)
        # Authelia rereads its users database when the file changes, but a
        # change within half a second of its last reread is dropped, not
        # deferred: Authelia would keep the state before it (a disabled account
        # still able to log in) until some later change. So the file is only
        # written when it changes (a rewrite starts that half second too), and
        # never sooner than `spacing` after the last write.
        if !(isfile(cfg.users_file) && read(cfg.users_file, String) == users)
            delay = writer.users_written + writer.spacing - time()
            delay > 0 && sleep(delay)
            atomic_write(io -> write(io, users), cfg.users_file; mode = 0o600)
            writer.users_written = time()
        end
        authelia = render_authelia_config(auth, authelia_secrets(root.state_dir), smtp_settings(root.state_dir))
        atomic_write(io -> write(io, authelia), authelia_config_file(cfg); mode = 0o600)
    end
    return nothing
end

# What stands in front of the server: behind the proxy Caddy, whose Caddyfile
# carries the worker credentials; behind a tunnel nothing of ours.
function write_front!(auth::ProxyAuth, root::ServerState)
    cfg = auth.config
    caddyfile = lock(() -> render_caddyfile(auth, values(root.worker_credentials[])), root.lock)
    candidate = cfg.caddyfile * ".new"
    atomic_write(io -> write(io, caddyfile), candidate; mode = 0o600)
    try
        check_caddyfile(cfg, candidate)
    catch
        rm(candidate; force = true)
        rethrow()
    end
    mv(candidate, cfg.caddyfile; force = true)
    return nothing
end
write_front!(::TunnelAuth, ::ServerState) = nothing

# ── Worker credentials ───────────────────────────────────────────────────────

"""
    add_worker_credential!(state, owner) -> String

Issue a worker credential for `owner` ("Add worker"): checked on `/w` from now
on, by Caddy behind the proxy and by the server itself on a trusted network.
Returns `name:password`, the only time the password exists outside its hashes;
the install command carries it to the new machine.
"""
function add_worker_credential!(state::ServerState, owner::AbstractString)
    root = root_state(state)
    name = "w-" * bytes2hex(rand(Random.RandomDevice(), UInt8, 4))
    password = bytes2hex(rand(Random.RandomDevice(), UInt8, 24))
    cred = WorkerCredential(name, caddy_password_hash(root.auth, password), String(owner), now(UTC),
                            credential_digest(password))
    lock(root.lock) do
        root.worker_credentials[][name] = cred
        save_worker_credentials!(root)
    end
    apply_proxy!(root)
    safe_notify!(root.worker_credentials)
    @info "worker credential issued" name owner
    return name * ":" * password
end

"""
    revoke_worker_credential!(state, name) -> Bool

Take a worker credential back: it is refused from now on, and a worker that is
connected with it is disconnected (its reconnect meets the refusal).
"""
function revoke_worker_credential!(state::ServerState, name::AbstractString)
    root = root_state(state)
    removed = lock(root.lock) do
        c = pop!(root.worker_credentials[], String(name), nothing)
        c === nothing || save_worker_credentials!(root)
        c
    end
    removed === nothing && return false
    apply_proxy!(root)
    safe_notify!(root.worker_credentials)
    for (wid, w) in lock(() -> collect(root.workers[]), root.lock)
        w.credential == name || continue
        link = worker_link(root, wid)
        link === nothing || WorkerLink.kill!(link, "the worker's credential was revoked")
    end
    @info "worker credential revoked" name
    return true
end

# ── Accounts ─────────────────────────────────────────────────────────────────

# Change the accounts, then persist them and hand them to Authelia.
function update_accounts!(f::Function, state::ServerState)
    root = root_state(state)
    proxy_config(root.auth)
    lock(root.lock) do
        f(root.accounts[])
        save_accounts!(root)
    end
    apply_proxy!(root)
    safe_notify!(root.accounts)
    return nothing
end

function account(state::ServerState, name::AbstractString)
    a = lock(() -> get(root_state(state).accounts[], String(name), nothing), state.lock)
    a === nothing && error("there is no account '$(name)'")
    return a
end

# The server must keep an admin who can log in, and nobody locks themselves out.
function check_admin_remains(state::ServerState, name::AbstractString)
    state.user !== nothing && state.user.name == name &&
        error("you cannot do that to your own account")
    others = lock(state.lock) do
        count(a -> a.name != name && is_admin(a) && !a.disabled, values(root_state(state).accounts[]))
    end
    others == 0 && error("'$(name)' is the last admin who can log in")
    return nothing
end

"""
    Authenticator

An account's second factor, registered by the server (`register_authenticator!`):
`uri` is what an authenticator app or a password manager takes (`otpauth://…`),
`qr` the same as a QR code (PNG). Shown once, to whoever the account is for.
"""
struct Authenticator
    uri::String
    qr::Vector{UInt8}
end

"""
    register_authenticator!(state, name) -> Authenticator

Give `name` a new authenticator (a one-time-code secret), replacing any before
it. Registered with Authelia by the server, so nobody has to confirm who they are
by mail first, which is Authelia's own way of adding one. Signed in with it, a
passkey is added on Authelia's settings page without mail too
(`skip_second_factor`), and then signs in alone.
"""
function register_authenticator!(state::ServerState, name::AbstractString)
    cfg = proxy_config(state.auth)
    config = authelia_config_file(cfg)
    migrate_authelia_storage(cfg)
    authenticator = mktempdir() do dir
        png = joinpath(dir, "qr.png")
        out = read(`$(cfg.authelia_bin) storage user totp generate $(name) --force --config $(config) --path $(png)`, String)
        uri = match(r"with URI '(otpauth://[^']+)'", out)
        uri === nothing && error("`authelia storage user totp generate` printed no URI: $(out)")
        Authenticator(String(uri[1]), read(png))
    end
    @info "authenticator registered" name
    return authenticator
end

# Authelia's database at its current schema: a fresh install has none before
# Authelia first starts. Authelia calls a database that is up to date already an
# error; for us it is the common case.
function migrate_authelia_storage(cfg::ProxyConfig)
    out = IOBuffer()
    p = run(pipeline(ignorestatus(`$(cfg.authelia_bin) storage migrate up --config $(authelia_config_file(cfg))`);
                     stdout = out, stderr = out))
    text = String(take!(out))
    success(p) || occursin("schema already up to date", text) ||
        error("`authelia storage migrate up` failed: $(strip(text))")
    return nothing
end

"""
    add_account!(state, name; display_name, email, groups) -> (; password, authenticator)

A new login in `groups` ("admins" makes an admin), accepted by Authelia once it
rereads its users database (it watches the file). Returns the account's password,
generated by Authelia, and its authenticator, for its owner; they exist nowhere
else.
"""
function add_account!(state::ServerState, name::AbstractString;
                      display_name::AbstractString = name, email::AbstractString = "",
                      groups::Vector{String} = String[])
    cfg = proxy_config(state.auth)
    valid_name(name) ||
        error("an account name is letters, digits, '.', '_' and '-' (got '$(name)')")
    haskey(root_state(state).accounts[], name) && error("there is an account '$(name)' already")
    pw = authelia_random_password(cfg)
    acct = Account(String(name), isempty(display_name) ? String(name) : String(display_name),
                   String(email), groups, false, pw.hash)
    update_accounts!(state) do accounts
        # Checked again under the lock: two requests for one name, one account.
        haskey(accounts, acct.name) && error("there is an account '$(acct.name)' already")
        accounts[acct.name] = acct
    end
    @info "account added" name groups
    # Only once the account is ours: registering replaces what is there, and a
    # name someone else holds must keep theirs. An account without one does not
    # stay: nobody could log in with it.
    authenticator = try
        register_authenticator!(state, acct.name)
    catch
        update_accounts!(accounts -> delete!(accounts, acct.name), state)
        rethrow()
    end
    return (password = pw.password, authenticator)
end

"How someone adds an authenticator: once, from what the server shows them."
const AUTHENTICATOR_HELP = "Scan it with an authenticator app or your password manager, or paste the link there."

qr_data_uri(a::Authenticator) = "data:image/png;base64," * Base64.base64encode(a.qr)

"An authenticator on the dashboard, for whoever it is shown to once."
authenticator_dom(a::Authenticator) =
    DOM.div(DOM.img(src = qr_data_uri(a), alt = "authenticator QR code", class = "bt-admin-qr"),
            DOM.div(AUTHENTICATOR_HELP; class = "bt-admin-muted"),
            DOM.code(a.uri; class = "bt-admin-uri"))

"A new random password for `name`, generated by Authelia; returned once."
function reset_account_password!(state::ServerState, name::AbstractString)
    a = account(state, name)
    pw = authelia_random_password(proxy_config(state.auth))
    update_accounts!(_ -> (a.password_hash = pw.hash), state)
    return pw.password
end

"""
    set_account_disabled!(state, name, disabled)

Authelia refuses a disabled account's next request; its open tabs are closed here,
since an open websocket is never re-checked.
"""
function set_account_disabled!(state::ServerState, name::AbstractString, disabled::Bool)
    a = account(state, name)
    disabled && is_admin(a) && check_admin_remains(state, name)
    update_accounts!(_ -> (a.disabled = disabled), state)
    disabled && close_user_sessions!(state, name)
    return nothing
end

"""
    set_account_groups!(state, name, groups)

Put `name` in exactly `groups`. "admins" makes an admin; any other group is one
workers can be shared with (`share_worker!`).
"""
function set_account_groups!(state::ServerState, name::AbstractString, groups::Vector{String})
    a = account(state, name)
    is_admin(a) && !("admins" in groups) && check_admin_remains(state, name)
    update_accounts!(_ -> (a.groups = groups), state)
    # The groups arrive with the next request through Authelia: reload the tabs.
    close_user_sessions!(state, name)
    return nothing
end

set_account_admin!(state::ServerState, name::AbstractString, admin::Bool) =
    set_account_groups!(state, name, admin ? union(account(state, name).groups, ["admins"]) :
                                             setdiff(account(state, name).groups, ["admins"]))

function remove_account!(state::ServerState, name::AbstractString)
    a = account(state, name)
    is_admin(a) && check_admin_remains(state, name)
    state.user !== nothing && state.user.name == name && error("you cannot remove your own account")
    update_accounts!(accounts -> delete!(accounts, a.name), state)
    close_user_sessions!(state, name)
    return nothing
end

"Every group some account is in, sorted."
all_groups(state::ServerState) =
    sort!(unique!(String[g for a in values(root_state(state).accounts[]) for g in a.groups]))

# ── Invites ──────────────────────────────────────────────────────────────────

"""
    create_invite!(state, groups; valid_for = Day(7)) -> String

A link that lets one person create their own account in `groups`, valid for
`valid_for`. The link is returned here only; the server keeps its token's hash.
"""
function create_invite!(state::ServerState, groups::Vector{String}; valid_for::Period = Day(7))
    root = root_state(state)
    proxy_config(root.auth)
    token = bytes2hex(rand(Random.RandomDevice(), UInt8, 32))
    t = now(UTC)
    invite = Invite(invite_id(token), groups, acting_owner(state), t, t + valid_for)
    lock(root.lock) do
        filter!(((_, i),) -> i.expires > t, root.invites[])   # expired ones go with it
        root.invites[][invite.id] = invite
        save_invites!(root)
    end
    safe_notify!(root.invites)
    @info "invite created" groups by = invite.created_by expires = invite.expires
    return install_base_url(root) * "/invite/" * token
end

function revoke_invite!(state::ServerState, id::AbstractString)
    root = root_state(state)
    removed = lock(root.lock) do
        i = pop!(root.invites[], String(id), nothing)
        i === nothing || save_invites!(root)
        i
    end
    removed === nothing && return false
    safe_notify!(root.invites)
    return true
end

"The invite a link carries, while it is good for an account; `nothing` otherwise."
function open_invite(state::ServerState, token::AbstractString)
    i = lock(() -> get(root_state(state).invites[], invite_id(token), nothing), state.lock)
    return (i === nothing || i.expires <= now(UTC)) ? nothing : i
end

"""
    redeem_invite!(state, token, name; display_name, email) -> (; password, authenticator)

Create the account an invite link offers, and use the link up. Returns the new
account's password and authenticator, which its owner sees once.
"""
function redeem_invite!(state::ServerState, token::AbstractString, name::AbstractString;
                        display_name::AbstractString = name, email::AbstractString = "")
    root = root_state(state)
    id = invite_id(token)
    # Taken out first, so two submissions of one link cannot make two accounts.
    invite = lock(() -> pop!(root.invites[], id, nothing), root.lock)
    invite === nothing && error("this invite link was used already or revoked")
    if invite.expires <= now(UTC)
        save_invites!(root)
        safe_notify!(root.invites)
        error("this invite link has expired")
    end
    login = try
        add_account!(root, name; display_name, email, groups = invite.groups)
    catch e
        # A name that is taken or not allowed: the link stays good for another try.
        lock(() -> (root.invites[][id] = invite), root.lock)
        rethrow()
    end
    save_invites!(root)
    safe_notify!(root.invites)
    @info "invite used" name invited_by = invite.created_by
    return login
end

"""
    redeem_setup!(state, token) -> (; password, authenticator)

Use up a setup link (an invite for an existing account): the account gets a new
password and authenticator, returned for its owner to see once.
"""
function redeem_setup!(state::ServerState, token::AbstractString)
    root = root_state(state)
    invite = lock(() -> pop!(root.invites[], invite_id(token), nothing), root.lock)
    invite === nothing && error("this setup link was used already or revoked")
    save_invites!(root)
    safe_notify!(root.invites)
    invite.expires <= now(UTC) && error("this setup link has expired")
    isempty(invite.account) && error("this is an invite for a new account, not a setup link")
    password = reset_account_password!(root, invite.account)
    @info "setup link used" name = invite.account
    return (password = password, authenticator = register_authenticator!(root, invite.account))
end

# The installer hands the first admin a setup link rather than codes: it writes
# the token's hash here, and the server files it with the invites when it starts.
setup_link_file(state::ServerState) = joinpath(state.state_dir, "setup_link.json")

function import_setup_link!(state::ServerState)
    f = setup_link_file(state)
    isfile(f) || return nothing
    d = JSON.parsefile(f)
    invite = Invite(String(d["token_sha256"]), String[], "installer", now(UTC),
                    DateTime(String(d["expires"])), String(d["account"]))
    lock(state.lock) do
        state.invites[][invite.id] = invite
        save_invites!(state)
    end
    rm(f)
    safe_notify!(state.invites)
    @info "setup link from the installer filed" account = invite.account expires = invite.expires
    return nothing
end

# /invite/<token>: open to anyone (the token is the proof), so it is plain HTML
# with a form, no dashboard session.
const INVITE_ROUTE_RE = r"^/invite/([0-9a-f]{64})/?(?:$|\?)"

function add_invite_routes!(srv::Bonito.Server, state::ServerState)
    Bonito.route!(srv, INVITE_ROUTE_RE => function(context)
        invite_response(state.auth, state, context.request, String(context.match.captures[1]))
    end)
end

invite_response(::OpenAuth, state::ServerState, request, token::AbstractString) =
    invite_page(404, "Not found", "<p>This server has no accounts to invite anyone to.</p>")

function invite_response(auth::LoginAuth, state::ServerState, request, token::AbstractString)
    invite = open_invite(state, token)
    invite === nothing && return invite_page(404, "This invite is not valid",
        "<p>The link was used already, revoked, or has expired. Ask for a new one.</p>")
    isempty(invite.account) || return setup_response(auth, state, request, token, invite.account)
    request.method == "POST" ||
        return invite_page(200, "Create your account", invite_form(Dict{String,String}(), ""))
    form = form_fields(String(request.body))
    name = strip(get(form, "name", ""))
    display_name = strip(get(form, "display_name", ""))
    login = try
        redeem_invite!(state, token, name; display_name = isempty(display_name) ? name : display_name,
                       email = strip(get(form, "email", "")))
    catch e
        (e isa ErrorException || e isa ProcessFailedException || e isa Base.IOError) || rethrow()
        return invite_page(400, "Create your account",
                           invite_form(form, first(split(sprint(showerror, e), '\n'))))
    end
    return account_ready_page(auth, name, login)
end

# A setup link: the account exists; opening it (and confirming) gives it a new
# password and authenticator, and the page that makes a passkey.
function setup_response(auth::LoginAuth, state::ServerState, request, token::AbstractString, name::AbstractString)
    request.method == "POST" || return invite_page(200, "Set up your login", """
        <p>This sets up how <b>$(esc_html(name))</b> signs in: a passkey, or a password and an authenticator.
        The link works once.</p>
        <form method="post"><button type="submit">Set up my login</button></form>""")
    login = try
        redeem_setup!(state, token)
    catch e
        (e isa ErrorException || e isa ProcessFailedException || e isa Base.IOError) || rethrow()
        return invite_page(400, "Set up your login", "<p class=\"err\">$(esc_html(first(split(sprint(showerror, e), '\n'))))</p>")
    end
    return account_ready_page(auth, name, login)
end

function invite_form(form::AbstractDict, error_message::AbstractString)
    field(key, label, type = "text") = """
        <label>$(label)<input type="$(type)" name="$(key)" value="$(esc_html(get(form, key, "")))"></label>"""
    err = isempty(error_message) ? "" : "<p class=\"err\">$(esc_html(error_message))</p>"
    return """
        $(err)
        <form method="post">
        $(field("name", "Account name (letters, digits, '.', '_', '-')"))
        $(field("display_name", "Full name"))
        $(field("email", "Email", "email"))
        <button type="submit">Create account</button>
