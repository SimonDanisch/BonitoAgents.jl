# An action run from a button: `f()` returns a status line, or a failure the
# person should read (a name taken, the last admin, Caddy or Authelia refusing)
# is shown instead.
function admin_action!(status::Observable{String}, f::Function)
    msg = try
        f()
    catch e
        (e isa ErrorException || e isa ProcessFailedException || e isa Base.IOError ||
         e isa HTTP.Exceptions.HTTPError) || rethrow()
        @warn "account action failed" exception = (e, catch_backtrace())
        first(split(sprint(showerror, e), '\n'))
    end
    safe_set!(status, String(msg))
    return nothing
end

