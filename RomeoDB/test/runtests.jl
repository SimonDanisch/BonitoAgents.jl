    @testset "keeping up with the registry" begin
        # A package server on disk: each source a gzipped tarball at package/<uuid>/<tree>.
        server = mktempdir()
        function serve!(p, files)
            src = mktempdir()
            for (f, text) in files
                mkpath(dirname(joinpath(src, f)))
                write(joinpath(src, f), text)
            end
            path = mkpath(joinpath(server, "package", string(p.uuid)))
            open(joinpath(path, string(p.tree)), "w") do io
                gz = RomeoDB.CodecZlib.GzipCompressorStream(io)
                RomeoDB.Tar.create(src, gz)
                close(gz)
            end
        end
        version(name, v, i, tree) = RomeoDB.PackageVersion(Base.UUID(i), name, v, Base.SHA1(fill(tree, 20)), "")
        a1, a2 = version("Alpha", v"1.0.0", 1, 0x01), version("Alpha", v"1.1.0", 1, 0x02)
        b, gone = version("Beta", v"1.0.0", 2, 0x03), version("Gamma", v"1.0.0", 3, 0x04)
        serve!(a1, ["src/Alpha.jl" => "module Alpha\nold_function(x) = x\nend\n", "Project.toml" => "name = \"Alpha\"\n"])
        serve!(a2, ["src/Alpha.jl" => "module Alpha\nnew_function(x) = x\nend\n", "Project.toml" => "name = \"Alpha\"\n",
                    "test/runtests.jl" => "not kept"])
        serve!(b, ["src/Beta.jl" => "module Beta\nbeta(x) = x\nend\n", "README.md" => "# Beta\n"])
        # A package in a subdirectory gets its repository's README only as the main package
        sub(name, repo, subdir) = RomeoDB.PackageVersion(Base.UUID(9), name, v"1.0.0", Base.SHA1(zeros(UInt8, 20)), repo, subdir)
        @test RomeoDB.rootreadme_url(sub("SpeedyWeather", "https://github.com/SpeedyWeather/SpeedyWeather.jl.git", "SpeedyWeather")) ==
              "https://raw.githubusercontent.com/SpeedyWeather/SpeedyWeather.jl/HEAD/README.md"
        @test RomeoDB.rootreadme_url(sub("RingGrids", "https://github.com/SpeedyWeather/SpeedyWeather.jl.git", "RingGrids")) === nothing
        @test RomeoDB.rootreadme_url(sub("SpeedyWeather", "https://github.com/SpeedyWeather/SpeedyWeather.jl.git", "")) === nothing
        @test RomeoDB.rootreadme_url(sub("Foo", "https://gitlab.com/x/Foo.jl.git", "Foo")) === nothing
        dir = mktempdir()
        local idx = RomeoDB.Index(dir; server = "file://" * server)
        @test RomeoDB.update!(idx, [a1, b, gone]; stats = false) == Dict("ok" => 2, "fetch-failed" => 1, "dropped" => 0, "local" => 0)
        @test only(RomeoDB.definition(idx, "Alpha", "old_function")).version == "1.0.0"
        @test isfile(joinpath(RomeoDB.sourcedir(idx, b), "README.md"))

        s = RomeoDB.Server(idx)
        before = RomeoDB.sketchtable!(s)
        @test RomeoDB.sketchtable!(s) === before        # nothing changed, nothing read again
        # A new version replaces the old one, its cached source goes too, and the failed fetch is retried.
        other = RomeoDB.Index(dir; server = "file://" * server)
        @test RomeoDB.update!(other, [a2, b, gone]; stats = false) == Dict("fetch-failed" => 1, "ok" => 1, "dropped" => 1, "local" => 0)
        @test isempty(RomeoDB.definition(idx, "Alpha", "old_function"))
        @test only(RomeoDB.search(idx, "new_function")).version == "1.1.0"
        @test !isdir(RomeoDB.sourcedir(idx, a1)) && !isfile(joinpath(RomeoDB.sourcedir(idx, a2), "test", "runtests.jl"))
        @test only(r.n for r in RomeoDB.rows(idx, "SELECT count(*) AS n FROM packages WHERE status = 'fetch-failed'")) == 1
        # the server sees the other connection's commits and reads the sketches again
        @test RomeoDB.sketchtable!(s) !== before
        # extracting again from the cached sources replaces each package in place
        @test RomeoDB.build!(other, [a2, b]; replace = true) == Dict("ok" => 2)
        @test only(r.n for r in RomeoDB.rows(idx, "SELECT count(*) AS n FROM packages WHERE status = 'ok'")) == 2
        @test only(RomeoDB.search(idx, "new_function")).version == "1.1.0"
        # a package gone from the registry is dropped
        @test RomeoDB.update!(other, [b]; stats = false) == Dict("dropped" => 1, "local" => 0)
        @test isempty(RomeoDB.definition(idx, "Alpha", "new_function"))

        # Unregistered packages on this machine: a working folder's dev/ holds one, a
        # checkout of the registered Beta (left to the registry's) and a non-package.
        dev = mktempdir()
        mine = mkpath(joinpath(dev, "Mine", "src"))
        write(joinpath(dev, "Mine", "Project.toml"), "name = \"Mine\"\nuuid = \"$(Base.UUID(77))\"\nversion = \"0.2.0\"\n")
        write(joinpath(mine, "Mine.jl"), "module Mine\nexport tile_kernel\n\"Tiles on the GPU.\"\ntile_kernel(x) = x\nend\n")
        mkpath(joinpath(dev, "Beta", "src"))
        write(joinpath(dev, "Beta", "Project.toml"), "name = \"Beta\"\nuuid = \"$(b.uuid)\"\n")
        write(joinpath(dev, "Beta", "src", "Beta.jl"), "module Beta\nbeta_dev(x) = x\nend\n")
        mkpath(joinpath(dev, "notes"))
        @test RomeoDB.addlocal!(idx, dev, joinpath(dev, "Mine")) == 1    # Mine once, from the first folder
        h = only(RomeoDB.search(idx, "tiles"))
        @test h.package == "Mine" && h.islocal && h.repo == joinpath(dev, "Mine")
        @test occursin("[function, exported; local]  $(joinpath(dev, "Mine", "src", "Mine.jl")):4", RomeoDB.astext(h))
        @test RomeoDB.source(idx, h) == "tile_kernel(x) = x"
        @test isempty(RomeoDB.definition(idx, "Beta", "beta_dev"))
        @test occursin("[local", RomeoDB.astext(RomeoDB.package_info(idx, "Mine")))
        @test occursin("unregistered ones under $dev", RomeoDB.unknownpackage(idx, "Nope"))
        # update! reads them again, edits included
        write(joinpath(mine, "Mine.jl"), "module Mine\n\"Tiles on the GPU.\"\ntile_kernel2(x) = x\nend\n")
        @test RomeoDB.update!(other, [b]; stats = false) == Dict("dropped" => 0, "local" => 1)
        @test only(RomeoDB.search(idx, "tiles")).name == "tile_kernel2"
        @test RomeoDB.removelocal!(idx, dev, joinpath(dev, "Mine")) == 0
        @test isempty(RomeoDB.search(idx, "tiles"))

        # With an embedder, an update gives every package without a vector one, and a
        # package dropped takes its vector with it.
        vectors() = only(r.n for r in RomeoDB.rows(idx, "SELECT count(*) AS n FROM vectors"))
        @test RomeoDB.update!(other, [a2, b]; stats = false, embedder = ToyEmbedder())["embedded"] == 2
        @test vectors() == 2
        @test RomeoDB.update!(other, [b]; stats = false, embedder = ToyEmbedder()) ==
              Dict("dropped" => 1, "local" => 0, "embedded" => 0)
        @test vectors() == 1

        # download statistics: successful fetches (200, and the far more common 302), addresses outside CI
        csv = joinpath(mktempdir(), "requests.csv.gz")
        open(csv, "w") do io
            gz = RomeoDB.CodecZlib.GzipCompressorStream(io)
            write(gz, """
                "package_uuid","status","client_type","request_addrs","request_count"
                "$(b.uuid)","302","user",5,50
                "$(b.uuid)","200","ci",3,7
                "$(b.uuid)","404","user",100,100
                """)
            close(gz)
        end
        @test RomeoDB.downloads!(idx; url = "file://" * csv) == 1
        @test only(RomeoDB.rows(idx, "SELECT users, requests FROM downloads")) == (users = 5, requests = 57)
    end
