        s, sn, sf = canon(long).sketch, canon(near).sketch, canon(far).sketch
        @test RomeoDB.similarity(s, s) == 1.0
        @test RomeoDB.similarity(s, sn) > 0.6
        @test RomeoDB.similarity(s, sf) < 0.3
    end

