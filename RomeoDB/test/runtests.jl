"The single definition in `code`, as `extract` records it."
function onedef(code)
    dir = mktempdir()
    mkpath(joinpath(dir, "src"))
    write(joinpath(dir, "src", "P.jl"), "module P\n" * code * "\nend\n")
    defs = RomeoDB.extract(dir, "P").defs
    @assert length(defs) == 1 "expected one definition in: $code"
    return only(defs)
end
canon(code) = onedef(code).canon

# A toy embedder: a text is the bag of concepts its words name, normalized, so `mesh`
# and `grid` meet where no word does. Slot 8 holds every word it does not know.
struct ToyEmbedder end
const TOYCONCEPTS = Dict("grid" => 1, "grids" => 1, "mesh" => 1, "meshes" => 1, "coordinate" => 2,
                         "matrices" => 3, "stencil" => 4, "stencils" => 4, "tables" => 5, "rows" => 5)
function toyvector(text)
    v = zeros(Float32, 8)
    foreach(w -> v[get(TOYCONCEPTS, w.match, 8)] += 1, eachmatch(r"\w+", lowercase(text)))
    return v ./ sqrt(sum(abs2, v))
end
RomeoDB.embeddocument(::ToyEmbedder, text::AbstractString) = toyvector(text)
RomeoDB.embedquery(::ToyEmbedder, text::AbstractString) = toyvector(text)

const GRID = """
    \"\"\"
        meshgrid(vx, vy)

    Coordinate matrices from coordinate vectors.
    \"\"\"
    function meshgrid(vx::AbstractVector{T}, vy::AbstractVector{T}) where {T}
        m, n = length(vy), length(vx)
        gx = reshape(vx, 1, n)
        gy = reshape(vy, m, 1)
        return (repeat(gx, m, 1), repeat(gy, 1, n))
    end"""

"""
An index of four packages. GridA (much used, GPU dependency, documented module, a README
with badges) has `meshgrid` and a `Tables.rows` method; GridB the same `meshgrid` with
renamed arguments, a bare `rows` (it depends on Tables) and a docs page; GridC a near
copy, a `rows` without Tables and a README saying it runs on CUDA arrays (its only GPU
evidence); Other a generated copy of `meshgrid` and CUDA as a test dependency.
"""
function fixture()
    idx = RomeoDB.Index(mktempdir())
    variant = replace(GRID, "meshgrid" => "ndgrid2", "repeat(gy, 1, n)" => "repeat(gy, 1, n) .+ zero(T)")
    readme_a = """
        # GridA

        [![CI](https://github.com/x/GridA.jl/actions/workflows/CI.yml/badge.svg)](https://github.com/x)

        Coordinate **grids** for [stencil](https://en.wikipedia.org/wiki/Stencil) codes,
        on the CPU and on GPUs.

        ## Usage
        """
    pkgs = [("GridA", "\"\"\"\nGrids for GPU stencils.\n\"\"\"\n", GRID * "\nTables.rows(t::GridTable) = t.cols",
             "[deps]\nKernelAbstractions = \"$(Base.UUID(101))\"\nTables = \"$(Base.UUID(102))\"", readme_a, 1000),
            ("GridB", "", replace(GRID, "vx" => "xs", "vy" => "ys") * "\nrows(t::BT) = t.data",
             "[deps]\nTables = \"$(Base.UUID(102))\"", "", 10),
            ("GridC", "", variant * "\nrows(x) = x", "", "GridC works with CUDA arrays as well.\n", 1),
            ("Other", "", "f(d::Dict, k) = haskey(d, k) ? d[k] : nothing\npoint_edge_distance(p, a, b) = 0\ninclude(\"gen.jl\")",
             "[extras]\nCUDA = \"$(Base.UUID(103))\"", "", 0)]
    for (i, (name, moddoc, code, project, readme, users)) in enumerate(pkgs)
        p = RomeoDB.PackageVersion(Base.UUID(i), name, v"1.0.0", Base.SHA1(fill(UInt8(i), 20)), "")
        root = RomeoDB.sourcedir(idx, p)
        mkpath(joinpath(root, "src"))
        write(joinpath(root, "src", name * ".jl"), "$(moddoc)module $name\nexport meshgrid\n$code\nend\n")
        name == "Other" && write(joinpath(root, "src", "gen.jl"), "# Autogenerated by ProtoBuf.jl, do not edit\n" * GRID)
        write(joinpath(root, "Project.toml"), "name = \"$name\"\n$project\n")
        isempty(readme) || write(joinpath(root, "README.md"), readme)
        if name == "GridB"
            mkpath(joinpath(root, "docs", "src"))
            write(joinpath(root, "docs", "src", "tutorial.md"), "# Tutorial\n\nBuilding a staggered grid step by step.\n")
        end
        RomeoDB.store!(idx, p, "ok", RomeoDB.extract(root, name), RomeoDB.dependencies(root))
        RomeoDB.exec!(idx.db, "INSERT INTO downloads (uuid, users, requests) VALUES (?, ?, ?)",
                    (string(p.uuid), users, 10users))
    end
    RomeoDB.reindex_text!(idx)
    return idx
end

@testset "RomeoDB" begin
    @testset "canonical form: what counts as the same code" begin
        # Renaming every name a definition binds is the same code; the exact hash still differs.
        a, b = canon("f(x) = x + 1"), canon("g(y) = y + 1")
        @test a.renamed == b.renamed
        @test a.exact != b.exact
        # Literals are bucketed by kind.
        @test canon("f(x) = x + 1").renamed == canon("f(x) = x + 2").renamed
        @test canon("f(x) = x + 1").renamed != canon("f(x) = x + 1.0").renamed
        # A different callee is different code: globals keep their names.
        @test canon("f(x) = sin(x)").renamed != canon("f(x) = cos(x)").renamed
        # Keyword names in a call bind nothing, so they are not renamed away.
        @test canon("f(x) = sum(x; dims = 1)").renamed != canon("f(x) = sum(x; init = 1)").renamed
        # Named-tuple fields neither.
        @test canon("f(x) = (a = x,)").renamed != canon("f(x) = (b = x,)").renamed
        # A keyword keeps its name without a `;` too, and a field after a dot keeps its
        # name even when a local is called the same.
        @test canon("f(x) = sum(x, dims = 1)").renamed != canon("f(x) = sum(x, init = 1)").renamed
        @test canon("f(p) = p.x").renamed != canon("f(p) = p.y").renamed
        @test canon("function f(x)\n y = x.x\n y\nend").renamed == canon("function g(a)\n b = a.x\n b\nend").renamed
        # Copying constructors over different fields are not the same code ...
        @test canon("T(a; u = a.u) = T(u)").renamed != canon("T(b; v = b.v) = T(v)").renamed
        # ... but positional arguments stay bound, with defaults and at call sites.
        @test canon("f(x = 1) = g(x)").renamed == canon("f(y = 1) = g(y)").renamed
        @test canon("f(x; k = 1) = g(x; k)").renamed == canon("f(y; k = 1) = g(y; k)").renamed
        # Locals, loop variables, comprehension variables and type parameters are renamed.
        @test canon("""function f(xs::Vector{T}) where T
                           acc = zero(T)
                           for v in xs
                               acc += v
                           end
                           [w * 2 for w in xs], acc
                       end""").renamed ==
              canon("""function g(ys::Vector{S}) where S
                           s = zero(S)
                           for q in ys
                               s += q
                           end
                           [r * 2 for r in ys], s
                       end""").renamed
        # Recursion on the definition's own name survives a rename.
        @test canon("fib(n) = n < 2 ? n : fib(n - 1) + fib(n - 2)").renamed ==
              canon("fibo(k) = k < 2 ? k : fibo(k - 1) + fibo(k - 2)").renamed
        # Comments and layout are not code.
        @test canon("f(x) = x + 1  # one").exact == canon("f(x) =\n    x + 1").exact
    end

    @testset "canonical form: complexity and sketch" begin
        c = canon("""function f(x)
                         if x > 0 && x < 10
                             return 1
                         elseif x < 0
                             return 2
                         end
                         while x > 1
                             x -= 1
                         end
